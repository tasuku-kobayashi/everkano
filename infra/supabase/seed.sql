jst as (
  select (now() at time zone 'Asia/Tokyo')::date as today
),
scheduled as (
  select
    v.*,
    (
      select jst.today + v.day_offset + (case when v.day_offset > 0 then k else -k end)
        from generate_series(0, 6) as k
       where v.day_offset = 0
          or extract(isodow from jst.today + v.day_offset + (case when v.day_offset > 0 then k else -k end))
             = any (v.allowed_isodow::int[])
       order by k
       limit 1
    ) as local_day
  from v
  cross join jst
),
resolved as (
  select
    s.*,
    case
      when s.lead_time is not null
        then now() + s.lead_time::interval
      when s.day_offset = 0
       and (s.local_day + s.local_time::time) at time zone 'Asia/Tokyo' > now()
        then (s.local_day - 1 + s.local_time::time) at time zone 'Asia/Tokyo'
      else (s.local_day + s.local_time::time) at time zone 'Asia/Tokyo'
    end as published_at
  from scheduled as s
)
